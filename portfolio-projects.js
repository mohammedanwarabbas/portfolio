// script to generate company projects
function generateCards(data) {
  const companyProjects = data.categories.find(category => category.categoryId === 1).projects;
  const companyProjectsDiv = document.getElementById("company-projects");

  companyProjectsDiv.innerHTML = '<h1 class="main-heading mt-5">Company Contributions</h1>';

  companyProjects.forEach((project, index) => {
      const iconsHtml = project.technologyIcons
          .map(icon => `<img src="icons/${icon}-icon.svg" alt="${icon}">`)
          .join('<span class="separator"></span>');

      const liveButton = project.liveURL
          ? `<a class="px-3 btn btn-outline-dark" href="${project.liveURL}" target="_blank">View Live</a>`
          : "";
      const sourceCodeButton = project.sourceCode
          ? `<a class="px-3 btn btn-outline-dark" href="${project.sourceCode}" target="_blank">Source Code</a>`
          : "";

      const cardHtml = `
    <div data-aos="fade-up" data-aos-duration="1500"
      class="d-flex justify-content-center project-container row mx-auto my-5 rounded-4">
      <div class="project-body card col-md-9 col-lg-4">
        <div class="d-flex flex-column align-items-center justify-content-center card-body">
          <h3 class="card-title">
            <i class="bi bi-${index + 1}-circle-fill"></i> ${project.projectTitle}
          </h3>
          <div class="projects-section-tech-icon-section w-100 d-flex justify-content-center align-items-center">
            ${iconsHtml}
          </div>
          <p class="card-text project-description">${project.projectDescription}</p>
          ${liveButton}
          ${sourceCodeButton}
        </div>
      </div>
      <div class="project-image col-md-3 col-lg-3 border-1 border"
        style="background-image: url('img/${project.projectImage}'); background-size: cover; background-position: center;">
      </div>
    </div>
  `;

      companyProjectsDiv.insertAdjacentHTML("beforeend", cardHtml);
  });
}

// Pass the portfolioData to generateCards
generateCards(portfolioData);







